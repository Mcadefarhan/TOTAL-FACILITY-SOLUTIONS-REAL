const LanguageContext = createContext(null);

const getNestedValue = (obj, path) =>
  path.split('.').reduce((acc, key) => (acc == null ? undefined : acc[key]), obj);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem(STORAGE_KEY) || 'en');

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language === 'hi' ? 'hi' : 'en';
  }, [language]);

  const value = useMemo(() => {
    const t = (key, languageOverride) => {
      const targetLanguage = translations[languageOverride] ? languageOverride : language;
      return getNestedValue(translationOverrides[targetLanguage], key)
        ?? getNestedValue(translations[targetLanguage], key)
        ?? getNestedValue(translationOverrides.en, key)
        ?? getNestedValue(translations.en, key)
        ?? key;
    };
    return { language, setLanguage, t };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}
